#!/bin/sh
# GameForge -- PreToolUse (matcher: Write|Edit|MultiEdit|NotebookEdit)
#
# Stops Claude from hand-editing files the engine generates or owns. Editing these
# silently corrupts projects: Unity .meta GUIDs break every scene reference, Godot
# .godot/ and .uid files are regenerated, Unreal Intermediate/ and binary .uasset
# files cannot be meaningfully written as text.
#
#   deny -> engine caches, build output, binary engine assets
#   ask  -> files that are engine-managed but occasionally edited on purpose
#
# Disable with GAMEFORGE_PROTECT=off.

. "${CLAUDE_PLUGIN_ROOT:-$(dirname "$0")/..}/hooks/lib/common.sh"
gf_read_input
[ "${GAMEFORGE_PROTECT:-on}" = off ] && exit 0

FILE=$(gf_json_get .tool_input.file_path)
[ -n "$FILE" ] || FILE=$(gf_json_get .tool_input.notebook_path)
[ -n "$FILE" ] || exit 0

gf_require_game_project

# Normalise to a project-relative path with forward slashes.
REL=$(printf '%s' "$FILE" | tr '\\' '/')
ROOT=$(pwd | tr '\\' '/')
case "$REL" in "$ROOT"/*) REL=${REL#"$ROOT"/} ;; esac

deny() { gf_pretool_decision deny "GameForge: $REL $1"; }
ask() { gf_pretool_decision ask "GameForge: $REL $1"; }

case "$GF_ENGINE" in
  godot)
    case "$REL" in
      .godot/*|*/.godot/*) deny "is inside .godot/, Godot's regenerated editor cache. Change the source resource or project settings instead." ;;
      *.uid) deny "is a Godot UID file. Godot owns these; editing them breaks resource references. Move or rename files through the editor or keep the .uid next to its script." ;;
      *.import) ask "is a Godot import-settings file. Prefer changing import options in the editor's Import dock; edit by hand only if the user asked for it." ;;
    esac ;;
  unity)
    case "$REL" in
      Library/*|Temp/*|Obj/*|obj/*|Logs/*|UserSettings/*|Build/*|Builds/*) deny "is in a Unity-generated folder. Unity rebuilds it; edit Assets/ or ProjectSettings/ instead." ;;
      *.csproj|*.sln) deny "is regenerated by Unity on every script reload. Use asmdef files or Unity's External Tools settings instead." ;;
      *.meta) ask "is a Unity .meta file. Its GUID links every reference to this asset; changing it can break scenes and prefabs. Let Unity create .meta files, and only edit import settings here if the user asked for it." ;;
    esac ;;
  unreal)
    case "$REL" in
      Binaries/*|Intermediate/*|Saved/*|DerivedDataCache/*|.vs/*|*/Binaries/*|*/Intermediate/*) deny "is in an Unreal-generated folder that the build regenerates. Edit Source/, Config/ or Content/ through the editor instead." ;;
      *.uasset|*.umap) deny "is a binary Unreal asset. It cannot be written as text; make the change in the editor, through Python editor scripting, or an Unreal MCP bridge." ;;
    esac ;;
esac

# Web and shared rules.
case "$REL" in
  node_modules/*|*/node_modules/*) deny "is inside node_modules/. Change package.json or patch the dependency with patch-package instead." ;;
  dist/*|build/*|.vite/*|.next/*|.parcel-cache/*)
    case "$GF_ENGINE" in threejs|r3f|babylon|playcanvas|phaser|pixi|kaplay|excalibur)
      deny "is build output. Edit the source and rebuild." ;;
    esac ;;
esac

exit 0
